import { createHash } from 'node:crypto';
import { expectAppError } from '@/tests/support/domain';
import { b, collabApp } from '../support/domain';
import { UnconfiguredContentProcessor, type ObjectStorage } from '@/src/server/collab/files/object-storage';

describe('Verified multipart upload protocol', () => {
  it('rejects oversized and expired uploads, immutable-part conflicts, and implicit name replacement', async () => {
    const c = await collabApp(), uploads = c.collab.files.uploads;
    const storage = c.collab.files.storages.createStorage(c.owner, b({ type: 'PERSONAL', name: 'Conflicts' }));
    const root = c.collab.files.storages.root(c.owner, storage.id);
    const bytes = Buffer.from('one'), checksum = createHash('sha256').update(bytes).digest('hex'), objects = new Map<string, Buffer>();
    uploads.configure({ async putImmutable(key, value) { objects.set(key, Buffer.from(value)); }, async read(key) { return objects.get(key)!; } },
      { async process() { return { scanStatus: 'CLEAN', processed: true }; } });
    const input = { targetFolderId: root.id, desiredFileName: 'same.txt', expectedSizeBytes: bytes.length, expectedChecksum: checksum, mimeType: 'text/plain' };
    await expectAppError(() => uploads.create(c.owner, b({ ...input, expectedSizeBytes: 104857601, idempotencyKey: 'large' })), 'FILE_TOO_LARGE', 413);
    const first = uploads.create(c.owner, b({ ...input, idempotencyKey: 'first' }));
    const part = { partNumber: 1, dataBase64: bytes.toString('base64'), checksum };
    await uploads.part(c.owner, first.id, b(part));
    const other = Buffer.from('two');
    await expectAppError(() => uploads.part(c.owner, first.id, b({ partNumber: 1, dataBase64: other.toString('base64'), checksum: createHash('sha256').update(other).digest('hex') })), 'UPLOAD_PART_CONFLICT', 409);
    await uploads.complete(c.owner, first.id, b());
    const conflict = uploads.create(c.owner, b({ ...input, idempotencyKey: 'conflict' }));
    await uploads.part(c.owner, conflict.id, b(part));
    await expectAppError(() => uploads.complete(c.owner, conflict.id, b()), 'FILE_NAME_CONFLICT', 409);
    expect(c.state.driveFileVersions).toHaveLength(1);
    const renamed = uploads.create(c.owner, b({ ...input, idempotencyKey: 'renamed', conflictMode: 'RENAME' }));
    await uploads.part(c.owner, renamed.id, b(part)); await uploads.complete(c.owner, renamed.id, b());
    expect(c.state.driveFiles).toHaveLength(2);
    expect(new Set(c.state.driveFiles.map(file => file.name)).size).toBe(2);
    c.state.uploadSessions.find(row => row.id === conflict.id)!.expiresAt = new Date(0);
    await expectAppError(() => uploads.part(c.owner, conflict.id, b(part)), 'UPLOAD_SESSION_EXPIRED', 410);
  });
  it('reserves quota, validates bytes and completes idempotently without leaking object identities', async () => {
    const c = await collabApp(), s = c.collab.files.storages, uploads = c.collab.files.uploads;
    const storage = s.createStorage(c.owner, b({ type: 'PERSONAL', name: 'Upload' })), root = s.root(c.owner, storage.id);
    const bytes = Buffer.from('safe sample'), checksum = createHash('sha256').update(bytes).digest('hex');
    const objects = new Map<string, Buffer>();
    const adapter: ObjectStorage = { async putImmutable(key, value) { objects.set(key, Buffer.from(value)); }, async read(key) { return objects.get(key)!; } };
    uploads.configure(adapter, new UnconfiguredContentProcessor());
    const input = { targetFolderId: root.id, desiredFileName: 'sample.txt', expectedSizeBytes: bytes.length, expectedChecksum: checksum, mimeType: 'text/plain', idempotencyKey: 'same-upload' };
    const session = uploads.create(c.owner, b(input));
    expect(uploads.create(c.owner, b(input)).id).toBe(session.id);
    await expectAppError(() => uploads.create(c.owner, b({ ...input, desiredFileName: 'other.txt' })), 'UPLOAD_IDEMPOTENCY_CONFLICT', 409);
    await uploads.part(c.owner, session.id, b({ partNumber: 1, dataBase64: bytes.toString('base64'), checksum }));
    const liveStorage = c.state.fileStorages.find(row => row.id === storage.id)!;
    liveStorage.isReadOnly = true;
    expect(uploads.get(c.owner, session.id).id).toBe(session.id);
    await expectAppError(() => uploads.part(c.owner, session.id, b({ partNumber: 1, dataBase64: bytes.toString('base64'), checksum })), 'STORAGE_READ_ONLY', 409);
    liveStorage.isReadOnly = false;
    await expectAppError(() => uploads.complete(c.owner, session.id, b()), 'FILE_PROCESSOR_UNAVAILABLE', 503);
    expect(c.state.driveFiles).toHaveLength(0);
    uploads.configure(adapter, { async process(value) { expect(value).toEqual(bytes); return { scanStatus: 'CLEAN', processed: true }; } });
    const complete = await uploads.complete(c.owner, session.id, b());
    expect(complete.status).toBe('COMPLETED');
    expect((await uploads.complete(c.owner, session.id, b())).resultVersionId).toBe(complete.resultVersionId);
    expect(c.state.driveFileVersions).toHaveLength(1); expect(c.state.driveFiles[0].status).toBe('ACTIVE');
    expect(JSON.stringify(uploads.get(c.owner, session.id))).not.toMatch(/objectKey|\/objects\//);
  });
  it('keeps malware blocked and prevents reservations from overcommitting quota', async () => {
    const c = await collabApp(), s = c.collab.files.storages, uploads = c.collab.files.uploads;
    const storage = s.createStorage(c.owner, b({ type: 'PERSONAL', name: 'Quota' })), root = s.root(c.owner, storage.id);
    const bytes = Buffer.from('blocked'), checksum = createHash('sha256').update(bytes).digest('hex'), objects = new Map<string, Buffer>();
    uploads.configure({ async putImmutable(key, value) { objects.set(key, value); }, async read(key) { return objects.get(key)!; } }, { async process() { return { scanStatus: 'BLOCKED', processed: false }; } });
    c.state.workspaces.find(row => row.id === c.owner.workspaceId)!.settings.fileStorageQuotaBytes = bytes.length;
    const input = { targetFolderId: root.id, desiredFileName: 'bad.txt', expectedSizeBytes: bytes.length, expectedChecksum: checksum, mimeType: 'text/plain', idempotencyKey: 'blocked' };
    const session = uploads.create(c.owner, b(input));
    await expectAppError(() => uploads.create(c.owner, b({ ...input, idempotencyKey: 'over-quota' })), 'STORAGE_QUOTA_EXCEEDED', 409);
    await uploads.part(c.owner, session.id, b({ partNumber: 1, dataBase64: bytes.toString('base64'), checksum }));
    await uploads.complete(c.owner, session.id, b());
    expect(c.state.driveFiles[0].status).toBe('BLOCKED'); expect(c.state.driveFileVersions[0].scanStatus).toBe('BLOCKED');
  });
  it('keeps scanned but unprocessed bytes unavailable through old-Version restoration', async () => {
    const c = await collabApp(), s = c.collab.files.storages, uploads = c.collab.files.uploads;
    const storage = s.createStorage(c.owner, b({ type: 'PERSONAL', name: 'Processing' })), root = s.root(c.owner, storage.id);
    const bytes = Buffer.from('pending'), checksum = createHash('sha256').update(bytes).digest('hex'), objects = new Map<string, Buffer>();
    const adapter: ObjectStorage = { async putImmutable(key, value) { objects.set(key, value); }, async read(key) { return objects.get(key)!; } };
    uploads.configure(adapter, { async process() { return { scanStatus: 'CLEAN', processed: false }; } });
    const session = uploads.create(c.owner, b({ targetFolderId: root.id, desiredFileName: 'pending.txt', expectedSizeBytes: bytes.length, expectedChecksum: checksum, mimeType: 'text/plain', idempotencyKey: 'pending' }));
    await uploads.part(c.owner, session.id, b({ partNumber: 1, dataBase64: bytes.toString('base64'), checksum }));
    const pending = await uploads.complete(c.owner, session.id, b());
    const file = c.state.driveFiles[0];
    await expectAppError(() => c.collab.files.records.restoreVersion(c.owner, file.id, pending.resultVersionId!, b({ version: file.version })), 'FILE_QUARANTINED', 409);
    uploads.configure(adapter, { async process() { return { scanStatus: 'CLEAN', processed: true }; } });
    expect((await uploads.complete(c.owner, session.id, b())).status).toBe('PROCESSING');
    const runner = c.collab.files.uploadProcessing, now = new Date(Date.now() + 3000), token = c.collab.support.id();
    expect(runner.claimDue(1, token, now)).toEqual([session.id]);
    const ticket = runner.prepare(session.id, token, now)!;
    expect(runner.finish(ticket, await runner.deliver(ticket), now)).toBe(true);
    const finished = uploads.get(c.owner, session.id);
    expect(finished.resultVersionId).toBe(pending.resultVersionId); expect(c.state.driveFileVersions).toHaveLength(1);
    expect(file.status).toBe('ACTIVE');
  });
});
